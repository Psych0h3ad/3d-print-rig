"""Fit smooth, fixed-length display bows; never a PTFE material simulation.

Fitting requires NumPy/SciPy offline; combining receipts uses only stdlib.
Inputs are the exact public Ender-3 receipts.
Frame boxes guide the fit; the release auditor checks exported triangles.
"""
import argparse
import gzip
import hashlib
import json
import math
from pathlib import Path

# These source receipts bind the measured pneumatic-joint faces. Updating them
# requires checking the native source features again before regenerating bows.
MANIFEST_SHA = 'e4c230fb2d228af5c7670b62bffddc675840766445269bfec9b6790db835646f'
PROFILE_SHA = 'c10ef0e862cbc2cc065e79153a1ec9da8ec60b0adeef4d5f24290156787f4c03'
MODEL_SHA = 'ef494370b069a5e8bdbdb45640aab791a822106c0f1636807342ebefe1ecc1cd'
LENGTH = 450
FITTINGS = {
    'stock': [-84.17249999999962, 241.91036372880058, -30.29700000000281],
    'belted': [-85.06495622543252, 229.247694852173, -28.323526418304],
}
X = list(range(-100, 101, 25))
Z = list(range(-50, 191, 10))
HARMONICS = 6


def combine_receipts(stock, belted, *, newline='\n'):
    """Validate fit receipts and return JS, without IO or scientific dependencies.

    Pins attest to the recorded inputs, not physical fit. Legacy receipts with
    unknown provenance must be verified separately, never assigned pins here.
    """
    sources = [(stock, 'stock'), (belted, 'belted')]
    pins = {'source_manifest_sha256': MANIFEST_SHA,
            'source_profile_sha256': PROFILE_SHA, 'source_model_sha256': MODEL_SHA}
    metadata = {'schema': 'ender-bowden-angular-bows-v1', 'length_mm': LENGTH,
                'preview_length_assumption': True, 'fitting_radius_mm': 2,
                'shape_threshold_mm': 34, 'frame_guide_clearance_mm': 3,
                'x_mm': X, 'z_mm': Z}

    def require(condition, message):
        if not condition:
            raise ValueError(message)

    def finite(value):
        return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)

    # Validate both inputs' provenance before accepting their parameters.
    for source, fitting in sources:
        require(isinstance(source, dict), f'{fitting}: expected a fit receipt')
        for key, expected in pins.items():
            require(source.get(key) == expected, f'{fitting}: missing or stale {key}')
        require(source.get('fitting') == fitting, f'{fitting}: wrong fitting receipt')
    weights = [math.pi*(i+1)*(-1)**(i+1) for i in range(HARMONICS)]
    for source, fitting in sources:
        for key, expected in metadata.items():
            require(key in source and source[key] == expected, f'{fitting}: invalid {key}')
        parameters = source.get('parameters')
        require(isinstance(parameters, list) and len(parameters) == len(Z), f'{fitting}: invalid parameter rows')
        for row in parameters:
            require(isinstance(row, list) and len(row) == len(X), f'{fitting}: invalid parameter columns')
            for v in row:
                require(isinstance(v, list) and len(v) == 2*HARMONICS and all(finite(n) for n in v),
                        f'{fitting}: invalid coefficients')
                require(abs(1.5*math.pi+sum(n*w for n, w in zip(v[:HARMONICS], weights))) < 1e-5
                        and abs(sum(n*w for n, w in zip(v[HARMONICS:], weights))) < 1e-5,
                        f'{fitting}: invalid neck constraints')
        observations = source.get('observations')
        require(isinstance(observations, list) and len(observations) == len(X)*len(Z),
                f'{fitting}: invalid observations')
        for observation in observations:
            require(isinstance(observation, dict), f'{fitting}: invalid observation')
            error, gap = observation.get('endpoint_error_mm'), observation.get('minimum_constraint')
            require(finite(error) and 0 <= error < 1e-4 and finite(gap) and gap >= -1e-6,
                    f'{fitting}: failed observation')
    # Preserve the existing field order and serialization bytes. Copy only pins
    # verified above; do not manufacture provenance for unverified receipts.
    data = {k: stock[k] for k in ['schema', 'length_mm', 'preview_length_assumption', 'fitting_radius_mm',
            'shape_threshold_mm', 'frame_guide_clearance_mm', 'source_manifest_sha256', 'x_mm', 'z_mm']}
    data.update(source_profile_sha256=stock['source_profile_sha256'], source_model_sha256=stock['source_model_sha256'],
                harmonics=HARMONICS, stock=stock['parameters'], belted=belted['parameters'])
    require(newline in ('\n', '\r\n'), 'Unsupported output newline')
    return (newline.join(['// Generated by scripts/generate_ender_bowden_shapes.py from pinned public fittings.',
                          'export const enderBowdenShapes='+json.dumps(data, separators=(',', ':'), allow_nan=False)+';', '']))


def _initialize_generation_math():
    """Load the unchanged numerical fitting machinery only for generation."""
    global np, cumulative_simpson, simpson, brentq, minimize, HEAD, T, FREQ, END_WEIGHTS, S, C
    import numpy as np
    from scipy.integrate import cumulative_simpson, simpson
    from scipy.optimize import brentq, minimize
    HEAD = np.array([6.112061443398004, 211.388931744161, 63.6999999999979])
    T = np.linspace(0, 1, 257)
    FREQ = np.pi * np.arange(1, HARMONICS+1)
    END_WEIGHTS = FREQ * np.cos(FREQ)
    S = np.sin(T[:, None] * FREQ)
    C = np.cos(T[:, None] * FREQ)


def curve(v):
    a, b = v[:HARMONICS], v[HARMONICS:]
    theta = 1.5 * np.pi * T + S @ a
    phi = S @ b
    dt = 1.5 * np.pi + C @ (a * FREQ)
    dp = C @ (b * FREQ)
    ddt = -S @ (a * FREQ**2)
    ddp = -S @ (b * FREQ**2)
    st, ct, sp, cp = np.sin(theta), np.cos(theta), np.sin(phi), np.cos(phi)
    tangent = np.c_[ct*cp, st*cp, sp]
    d = np.c_[-st*cp*dt-ct*sp*dp, ct*cp*dt-st*sp*dp, cp*dp]
    dd = np.c_[-ct*cp*(dt*dt+dp*dp)+2*st*sp*dt*dp-st*cp*ddt-ct*sp*ddp,
               -st*cp*(dt*dt+dp*dp)-2*ct*sp*dt*dp+ct*cp*ddt-st*sp*ddp,
               -sp*dp*dp+cp*ddp]
    points = LENGTH * cumulative_simpson(tangent, x=T, axis=0, initial=0)
    return points, d, dd, dt, phi


def energy(v):
    _, d, dd, _, _ = curve(v)
    return simpson(np.sum(d*d, axis=1), x=T) + .008*simpson(np.sum(dd*dd, axis=1), x=T)


def seed(target):
    dx, dy, dz = target
    def derivative(h):
        return np.c_[3*h*(1-T)*(1-3*T)+dx*6*T*(1-T),
                     3*h*T*(2-3*T)+dy*6*T*(1-T), dz*6*T*(1-T)]
    h = brentq(lambda n: simpson(np.linalg.norm(derivative(n), axis=1), x=T)-LENGTH, 1, 1000)
    d = derivative(h)
    theta = np.unwrap(np.arctan2(d[:, 1], d[:, 0]))
    phi = np.arctan2(d[:, 2], np.linalg.norm(d[:, :2], axis=1))
    return np.r_[np.linalg.lstsq(S, theta-1.5*np.pi*T, rcond=None)[0],
                 np.linalg.lstsq(S, phi, rcond=None)[0]]


def fit(fitting, boxes, seed_table=None):
    start = np.array(FITTINGS[fitting])
    lows, highs = np.array([b[0] for b in boxes]), np.array([b[1] for b in boxes])
    table, previous_row, observations = [], [], []
    for z in Z:
        row = []
        for ix, x in enumerate(X):
            target = HEAD + [x, 0, 0] - start
            origin = start + [0, z, 0]
            def inequalities(v):
                p, d, _, turn, phi = curve(v)
                world = p + origin
                q = np.maximum(lows[:, None, :]-world[None, :, :], world[None, :, :]-highs[:, None, :])
                distance = np.linalg.norm(np.maximum(q, 0), axis=2)+np.minimum(q.max(axis=2), 0)
                gaps = ((distance-3)/50).ravel()
                return np.r_[LENGTH/34-np.linalg.norm(d, axis=1), gaps,
                             1.45+phi, 1.45-phi, p[:, 1]-(target[1]-1)]
            guesses = ([previous_row[ix]] if previous_row else []) + ([row[-1]] if row else []) + [seed(target)]
            if seed_table:
                old = np.array(seed_table[len(table)][ix])
                if len(old) == 8:
                    old = np.r_[old[:4], 0, 0, old[4:], 0, 0]
                guesses.append(old)
            candidates = []
            for guess in guesses:
                result = minimize(energy, guess, method='SLSQP', bounds=[(-5, 5)]*(2*HARMONICS),
                    constraints=[{'type': 'eq', 'fun': lambda v: (curve(v)[0][-1]-target)/100},
                                 {'type': 'eq', 'fun': lambda v: np.array([1.5*np.pi+v[:HARMONICS]@END_WEIGHTS,
                                                                         v[HARMONICS:]@END_WEIGHTS])},
                                 {'type': 'ineq', 'fun': inequalities}],
                    options={'maxiter': 300, 'ftol': 2e-9})
                error = float(np.linalg.norm(curve(result.x)[0][-1]-target))
                gap = float(np.min(inequalities(result.x)))
                neck = max(abs(1.5*np.pi+result.x[:HARMONICS]@END_WEIGHTS),
                           abs(result.x[HARMONICS:]@END_WEIGHTS))
                if error < 1e-4 and gap >= -1e-6 and neck < 1e-5:
                    candidates.append(result.x)
                    # Continue the neighbouring solution instead of changing
                    # the hose's winding class to chase a different minimum.
                    break
            if not candidates:
                raise ValueError(f'Unresolved bow: {fitting} X{x} Z{z}; error {error}; constraint {gap}')
            v = candidates[0]
            row.append(v)
            observations.append({'x': x, 'z': z, 'endpoint_error_mm': error,
                'minimum_constraint': gap,
                'radius_mm': float(LENGTH/np.max(np.linalg.norm(curve(v)[1], axis=1)))})
        previous_row = row
        table.append([v.tolist() for v in row])
        print(f'{fitting}: Z{z}, {len(table)*len(X)} bows', flush=True)
    return table, observations


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--assets', type=Path)
    parser.add_argument('--fitting', choices=FITTINGS)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--seed', type=Path, help='Optional prior angular solution table; every bow is refitted and checked.')
    parser.add_argument('--combine', type=Path, nargs=2, metavar=('STOCK_JSON', 'BELTED_JSON'))
    args = parser.parse_args()
    if args.combine:
        stock, belted = [json.loads(p.read_text('utf8')) for p in args.combine]
        javascript = combine_receipts(stock, belted)
        args.output.write_bytes(javascript.encode('utf8'))
        return
    if not args.assets or not args.fitting:
        parser.error('--assets and --fitting are required when fitting bows')
    _initialize_generation_math()
    root = Path(__file__).resolve().parents[1]
    index = json.loads((root/'site/COMMUNITY_MACHINES_ASSETS.json').read_text('utf8'))
    spec = index['machines']['ender3_stock_220']
    pin = spec['files']['assembly_manifest.json']
    assert pin['sha256'] == MANIFEST_SHA and spec['files']['model.glb']['decoded_sha256'] == MODEL_SHA
    raw = (args.assets/pin['path']).read_bytes()
    assert len(raw) == pin['bytes'] and hashlib.sha256(raw).hexdigest() == pin['sha256']
    manifest = json.loads(gzip.decompress(raw) if pin.get('encoding') == 'gzip' else raw)
    parts = {p['key']: p for p in manifest['parts']}
    profile_pin = spec['files']['machine_profile.json']
    assert profile_pin['sha256'] == PROFILE_SHA
    profile_raw = (args.assets/profile_pin['path']).read_bytes()
    assert len(profile_raw) == profile_pin['bytes'] and hashlib.sha256(profile_raw).hexdigest() == profile_pin['sha256']
    profile = json.loads(gzip.decompress(profile_raw) if profile_pin.get('encoding') == 'gzip' else profile_raw)
    hidden = set(profile['configurations']['stock__belted__none' if args.fitting == 'belted' else 'stock'].get('hidden_keys', []))
    candidates = [tuple(np.array(p) for p in row['native_bounds_mm']) for row in parts.values()
                  if row['group'] == 'fixed' and row['key'] not in hidden and row['native_bounds_mm'][1][1] >= 157]
    # A contained box adds no new design constraint. Native shapes and holes
    # are still inspected independently by the triangle auditor.
    boxes = [a for i, a in enumerate(candidates) if not any(i != j and np.all(a[0] >= b[0])
             and np.all(a[1] <= b[1]) and (np.any(a[0] > b[0]) or np.any(a[1] < b[1]) or j < i)
             for j, b in enumerate(candidates))]
    print(f'{args.fitting}: {len(boxes)} source-fixed obstacle guides', flush=True)
    seeds = json.loads(args.seed.read_text('utf8'))['parameters'] if args.seed else None
    values, observations = fit(args.fitting, boxes, seeds)
    data = dict(schema='ender-bowden-angular-bows-v1', fitting=args.fitting,
        length_mm=LENGTH, preview_length_assumption=True, fitting_radius_mm=2,
        shape_threshold_mm=34, frame_guide_clearance_mm=3, source_manifest_sha256=pin['sha256'],
        source_profile_sha256=profile_pin['sha256'], source_model_sha256=spec['files']['model.glb']['decoded_sha256'],
        x_mm=X, z_mm=Z, parameters=values, observations=observations)
    args.output.write_text(json.dumps(data, separators=(',', ':'))+'\n', encoding='utf8')


if __name__ == '__main__':
    main()
